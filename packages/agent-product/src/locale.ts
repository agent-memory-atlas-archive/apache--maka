export function copy(locale: string): Copy {
  const tag = locale.toLowerCase();
  return tag.startsWith('zh')
    ? tag.includes('hant') ||
      tag.startsWith('zh-tw') ||
      tag.startsWith('zh-hk') ||
      tag.startsWith('zh-mo')
      ? zhTW
      : zhCN
    : en;
}
